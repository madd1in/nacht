  function width(str) { let w = 0; for (const ch of norm(str)) w += adv(ch); return w - 1; }
  function hasFB(str) { for (const ch of norm(str)) if (!INDEX.has(ch)) return true; return false; }

  // opts: { align: 'left'|'center'|'right', shadow: color }
